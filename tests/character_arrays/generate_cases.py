#!/usr/bin/env python3
"""CHARACTER array, constructor, concatenation and fail-closed differential cases."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parent
cases=[]
def add(name,decl,body,want='',category='success',baseline='run',full=None):
    source=full or 'implicit none\n'+decl+'\n'+body+'\nend\n'
    (ROOT/'cases'/f'{name}.f90').write_text(source)
    cases.append(dict(name=name,source=f'cases/{name}.f90',category=category,baseline=baseline,expected_stdout=want))
add('requested','','','one  two  three one   four  three T F T',full=(ROOT.parent.parent/'examples/character_arrays.f90').read_text())
add('scalar_concat','','print *,"a"//"b", "a"//"b"=="ab", "ab"=="a"//"b"','ab T T')
add('concat_chain','','print *,"a"//"b"//"c",("a"//"b")//"c"','abcabc')
add('logical_precedence','','print *, .not."a"//"b"=="ab", "a"//"b"=="ab" .and. .true.','F T')
add('zero_length','character(0)::a(2)=["",""]','print *,size(a),a=="",a//"x"','2 T T xx')
add('typed_truncate','character(3)::a(3)=[character(3)::"abcd","b","cde"]','print *,a,a==["abc","b  ","cde"]','abcb  cde T T T')
add('typed_default','character::a(2)=[character::"ab","cd"]','print *,a','ac')
add('typed_empty','character(3)::a(0)=[character(3)::]','print *,size(a),kind(a),size(a//"x")','0 1 0')
add('typed_empty_slash','character(2)::a(0)=(/character(2)::/)','print *,size(a)','0')
add('slash_constructor','integer,parameter::n=3\ncharacter(n)::a(2)=(/character(len=n)::"x","yz"/)','print *,a','x  yz')
add('array_expansion','character(2)::a(2)=["ab","cd"]','print *,"!"//a,a//"?",a//a','!ab!cdab?cd?ababcdcd')
add('concat_array_pair','character(2)::a(2)=["ab","cd"]\ncharacter::b(2)=["x","y"]','print *,a//b,b//a','abxcdyxab ycd'.replace(' ',''))
add('constant_concat','character(3),parameter::a="a"//"b"\ncharacter(4)::b(2)=a//"c"','print *,b=="ab c",b','T T ab cab c')
add('parameter_array','character(4),parameter::a(2)=[character(2)::"a","bb"]','print *,a,a==["a   ","bb  "]','a   bb   T T')
add('parameter_scalar_expansion','character(3),parameter::a(2)="x"','print *,a=="x",a','T T x  x')
add('parameter_references','character(2),parameter::a(2)=["ab","cd"]\ncharacter(3),parameter::b(2)=a//"!"','print *,b','ab!cd!')
add('overlap_assignment','character(2)::a(3)=["ab","cd","ef"]','a=a(3:1:-1)\nprint *,a','efcdab')
add('overlap_concat','character(3)::a(3)=[character(3)::"a","b","c"]','a=a(3:1:-1)//a(1)\nprint *,a','c  b  a')
add('sections','character(2)::a(-1:2)=["aa","bb","cc","dd"]','a(0:2:2)="x"\nprint *,a,a(2:-1:-1)//"!"','aax ccx x !cc!x !aa!')
add('elements','character(2)::a(2)=["aa","bb"]','a(2)="xyz"\nprint *,a(1)//a(2),a','aaxyaa xy'.replace(' ',''))
add('rank_two','character(2)::a(2,2)="x"','a(:,1)=["ab","cd"]\na(1,2)="yz"\nprint *,a,"!"//a,a=="x"','abcdyzx !ab!cd!yz!x T F F T',category='success')
# Correct column-major comparison values are F F F T.
cases[-1]['expected_stdout']='abcdyzx  !ab!cd!yz!x  F F F T'
add('rank_two_sections','character(2)::a(2,2)="q"','a(:,1)=["ab","cd"]\na(:,2)=a(2:1:-1,1)\nprint *,a(1,:),a(:,2)//"!"','abcdcd!ab!')
add('nested_constructor','character(2)::a(4)=[character(2)::["a","b"],["c","d"]]','print *,a','a b c d')
add('constructor_array_items','character(2)::a(2)=["ab","cd"]\ncharacter(3)::b(5)','b=[character(3)::a,"e",a]\nprint *,b','ab cd e  ab cd')
add('empty_array_item','character(2)::a(0)\ncharacter(2)::b(1)','b=[character(2)::a,"z"]\nprint *,b','z')
add('constructor_trim','character(4)::a(2)','a=[character(4)::trim(" a "),trim("b  ")]\nprint *,a',' a  b')
add('comparison_padding','character(3)::a(2)=[character(3)::"a","b"]','print *,a=="a",a<"b",a/="b  ","b">=a','T F T F T F T T')
add('kind_unevaluated','character(2)::a(2)','print *,kind(a//"!"),kind([character(3)::a]),kind(a=="a")','1 1 4')
add('named_len_import','','','x  yz',full='module m\ninteger,parameter::n=3\nend module\nprogram p\nuse m\nimplicit none\ncharacter(n)::a(2)=[character(n)::"x","yz"]\nprint *,a\nend\n')
add('scalar_character_function','','','abc',full='program p\nimplicit none\nprint *,f()\ncontains\nfunction f() result(r)\ncharacter(3)::r\nr="a"//"bc"\nend function\nend\n')
add('untyped_length_mismatch','character(3)::a(2)=["a","bb"]','print *,a',category='reject',baseline='reject')
add('mixed_type','character(3)::a(2)=[character(3)::"a",2]','print *,a',category='reject',baseline='reject')
add('numeric_concat','','print *,1//2',category='reject',baseline='reject')
add('nonconstant_len','integer::n=3\ncharacter(n)::a','print *,a',category='reject',baseline='reject')
add('real_len','character(2.0)::a','print *,a',category='reject',baseline='reject')
add('oversize_len','character(65537)::a','print *,a',category='reject',baseline='skip')
add('typed_assumed_len','character(3)::a(1)=[character(*)::"x"]','print *,a',category='reject',baseline='reject')
add('nonconformable_concat','character::a(2),b(3)','print *,a//b',category='reject',baseline='reject')
add('array_uninitialized','character(2)::a(2)','print *,a',category='runtime',baseline='compile')
add('element_bounds','character(2)::a(2)="x"','print *,a(3)',category='runtime',baseline='compile')
add('zero_stride','character(2)::a(2)="x"\ninteger::step=0','print *,a(::step)',category='runtime',baseline='compile')
add('dynamic_shape','character::a(3)="a",b(2)="b"\ninteger::n=3','print *,a(:n)//b',category='runtime',baseline='compile')
add('empty_expansion','character(2)::a(0)\ncharacter::x','a=x',category='runtime',baseline='compile')
add('empty_concat_unevaluated','character(2)::a(0)\ncharacter::x','print *,size(a//x)','0')
add('untype_trim_boundary','character(2)::a(2)','a=[trim("a "),trim("b ")]')
add('trailing_comma','character(2)::a(1)=[character(2)::"x",]','print *,a',category='reject',baseline='reject')
add('trailing_comma_slash','character(2)::a(1)=(/character(2)::"x",/)','print *,a',category='reject',baseline='reject')
add('character_dummy_boundary','','x x',category='success',baseline='run',full='program p\nimplicit none\ncharacter(2)::a(2)="x"\ncall f(a)\ncontains\nsubroutine f(x)\ncharacter(2),intent(in)::x(:)\nprint *,x\nend subroutine\nend\n')
add('numeric_typed_boundary','integer::a(1)=[integer::1]','print *,a',category='reject',baseline='compile')
(ROOT/'manifest.json').write_text(json.dumps(dict(cases=cases),indent=2)+'\n')
print(f'Wrote {len(cases)} cases')
